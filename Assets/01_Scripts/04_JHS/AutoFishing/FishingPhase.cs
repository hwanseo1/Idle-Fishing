namespace JHS.Fishing
{
    // 자동 낚시 루프의 "지금 무슨 단계인가" 신호. 연출(애니메이션/이펙트)이 구독해 쓴다.
    // 컨트롤러는 이 값을 발행만 하고, 어떤 클립/이펙트로 보일지는 전혀 모른다(연출 분리).
    // ※ 세이브/데이터에 안 쓰이는 표현용 enum → 순서·값 자유롭게 늘려도 됨 (장비 enum과 달리 고정 아님).
    public enum FishingPhase
    {
        Idle,      // 낚시 안 함(메인스테이지 이탈/보스 등) — 쉬는 포즈
        Casting,   // 던지기 — 낚싯대 휘두름 (1회성)
        Waiting,   // 입질 대기 — 찌 떠 있는 루프
        Bite,      // 입질 — 반응 모션 (1회성)
        Reeling,   // 당기기 — 포획 시도 (1회성)
        Success,   // 포획 성공 — 어필 (잡힌 물고기는 OnFishCaught로 별도 전달)
        Fail       // 놓침 — 허탈 (수동 실패)
    }
}
